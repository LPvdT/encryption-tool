from __future__ import annotations

import os

import pytest

from encryption_tool.crypto import (
    EncryptionError,
    decrypt_data,
    encrypt_data,
)


@pytest.mark.parametrize("algorithm", ["AES-256-GCM", "ChaCha20-Poly1305"])
@pytest.mark.parametrize("payload", [b"", b"hello", b"\x00\xff\x10binary", os.urandom(4096)])
def test_round_trip(payload: bytes, algorithm: str) -> None:
    encrypted = encrypt_data(payload, "correct horse battery staple", algorithm)  # type: ignore[arg-type]
    assert decrypt_data(encrypted, "correct horse battery staple") == payload


def test_random_salt_and_nonce_produce_distinct_envelopes() -> None:
    first = encrypt_data(b"same", "password")
    second = encrypt_data(b"same", "password")
    assert first != second


def test_wrong_password_is_rejected() -> None:
    encrypted = encrypt_data(b"secret", "right")
    with pytest.raises(EncryptionError, match="incorrect password or damaged data"):
        decrypt_data(encrypted, "wrong")


@pytest.mark.parametrize("mutation", [0, 4, 5, 7, 22, -1])
def test_tampering_is_rejected(mutation: int) -> None:
    encrypted = bytearray(encrypt_data(b"secret", "password"))
    encrypted[mutation] ^= 0x01
    with pytest.raises(EncryptionError):
        decrypt_data(bytes(encrypted), "password")


@pytest.mark.parametrize("payload", [b"", b"ETK2", b"ETK2\x01", b"A" * 20])
def test_truncated_or_unknown_payload_is_rejected(payload: bytes) -> None:
    with pytest.raises(EncryptionError):
        decrypt_data(payload, "password")


def test_empty_password_is_rejected() -> None:
    with pytest.raises(ValueError, match="non-empty"):
        encrypt_data(b"data", "")


def test_unknown_algorithm_is_rejected() -> None:
    with pytest.raises(ValueError, match="Unsupported encryption algorithm"):
        encrypt_data(b"data", "password", "AES-128-CBC")  # type: ignore[arg-type]


def test_legacy_payload_remains_decryptable() -> None:
    # Fixture generated by the original v2.0 implementation's Scrypt format.
    from cryptography.hazmat.primitives.ciphers.aead import AESGCM
    from cryptography.hazmat.primitives.kdf.scrypt import Scrypt

    password = b"legacy-password"
    salt = bytes(range(16))
    nonce = bytes(range(12))
    key = Scrypt(salt=salt, length=32, n=2**14, r=8, p=1).derive(password)
    legacy = b"A" + salt + nonce + AESGCM(key).encrypt(nonce, b"legacy", None)
    assert decrypt_data(legacy, password.decode()) == b"legacy"
